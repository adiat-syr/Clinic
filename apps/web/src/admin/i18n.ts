export type AdminLocale = 'ru' | 'kk';
export function adminLocale(): AdminLocale {
  return typeof location !== 'undefined' &&
    new URLSearchParams(location.search).get('lang') === 'kk'
    ? 'kk'
    : 'ru';
}
export function adminHref(path: string, locale = adminLocale()) {
  return path + (locale === 'kk' ? '?lang=kk' : '');
}
export function labelName(value: { nameRu: string; nameKk?: string }) {
  return adminLocale() === 'kk' ? value.nameKk || value.nameRu : value.nameRu;
}
export function translate(value: string): string {
  if (adminLocale() === 'ru') return value;
  const key = value.replace(/\s+/g, ' ').trim();
  const translated = kk[key];
  return translated === undefined
    ? value
    : (value.startsWith(' ') ? ' ' : '') + translated + (value.endsWith(' ') ? ' ' : '');
}
